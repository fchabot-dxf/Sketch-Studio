// scripts/gen-origin-rules-index.mjs — TASK 803: GENERATES docs/ORIGIN-RULES.md, the INDEX of packages/core/origin-rules.js (never edited by hand).
// One line per rule: id + short name + links to its entry in the rules data, to its evidence and to the code that uses it. The statement lives ONLY in the data.
// Usage: node scripts/gen-origin-rules-index.mjs [--check]   (--check exits 1 when the committed file is stale; tests/origin-rules-803-node.test.js does the same)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RULES_FILE = 'packages/core/origin-rules.js';
export const INDEX_FILE = 'docs/ORIGIN-RULES.md';

const lineOf = (text, re) => { const i = text.split('\n').findIndex((l) => re.test(l)); return i < 0 ? null : i + 1; };
const esc = (r) => r.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** The WORK-LOG line of the heading of turn `id` ("## TURN 456 ..." / "## 2026-06-29 · SP1j-2 — ..."), or null. */
export function workLogLine(logText, id) {
  const e = esc(id);
  return lineOf(logText, new RegExp(`^## (?:${e}(?![\\w-])|.*·\\s*${e}(?![\\w-]))`));
}

export async function buildIndex(root = ROOT) {
  const mod = await import(pathToFileURL(path.join(root, RULES_FILE)).href);
  const src = fs.readFileSync(path.join(root, RULES_FILE), 'utf8');
  const log = fs.readFileSync(path.join(root, 'WORK-LOG.md'), 'utf8');
  const rel = (p) => `../${p}`;
  const ruleLink = (r) => { const n = lineOf(src, new RegExp(`^\\s*id: '${esc(r.id)}'`)); return `[entry](${rel(RULES_FILE)}#L${n})`; };
  const ev = (e) => {
    if (e.log) { const n = workLogLine(log, e.log); return n ? `[${e.log}](../WORK-LOG.md#L${n})` : `${e.log} (NOT FOUND)`; }
    if (e.file) return `[${e.file}](${rel(e.file)})`;
    if (e.url) return `[${e.url}](${e.url})`;
    return `note: ${e.note}`;
  };
  const code = (u) => { const [f, sym] = u.split('#'); return `[${path.posix.basename(f)}#${sym}](${rel(f)})`; };
  const out = [];
  out.push('# Shaper Origin / Studio rules: INDEX', '',
    '<!-- GENERATED by scripts/gen-origin-rules-index.mjs from packages/core/origin-rules.js. DO NOT EDIT BY HAND: run `node scripts/gen-origin-rules-index.mjs`. A test fails when this file is stale. -->', '',
    'This is an INDEX, not a copy: a rule\'s statement lives ONLY in [packages/core/origin-rules.js](../packages/core/origin-rules.js). Each line gives the rule\'s id and short name, then links to its entry, its evidence and the code that uses it.', '',
    '## How to add a rule', '',
    '1. Measure it on the machine (a photo of the screen, or a file the Origin / Studio wrote) and note where the evidence is (a WORK-LOG turn, a file, a Shaper help URL).',
    '2. Add the entry to `ORIGIN_RULES` in packages/core/origin-rules.js: `id`, `name`, `targets` (ONLY the targets the evidence covers: a finding measured in Studio is not assumed for the Origin, nor the other way round), `sev` (`error` = never legitimate, `warn` = sometimes legitimate, `info` = visibility, `null` = no static check), `status` (`measured` | `documented` | `assumed`), `statement`, `check` (a declarative row for the ONE validator, or `null`), `message`, `evidence`, `usedBy` (`file#symbol`).',
    '3. If the exporter writes it, add / read the form in the target\'s `forms` (`exportForm(name)`); the validator (`checkOriginRules`) and the exporter pick it up, and every download is checked.',
    '4. Run `node scripts/gen-origin-rules-index.mjs` and commit this file; `tests/origin-rules-803-node.test.js` checks every rule has evidence, a status and code that exists.', '',
    '## Targets', '');
  for (const t of mod.listTargets()) {
    const forms = Object.keys(mod.ORIGIN_TARGETS[t.id].forms);
    out.push(`- \`${t.id}\` (${t.name}): forms ${forms.map((f) => `\`${f}\``).join(', ')}`);
  }
  out.push('', '## Rules', '', `${mod.ORIGIN_RULES.length} rules. Format: \`id\` name [targets] severity / status: entry; evidence; code.`, '');
  for (const r of mod.ORIGIN_RULES) {
    out.push(`- \`${r.id}\` ${r.name} [${r.targets.join(', ')}] ${r.sev || 'no check'} / ${r.status}: ${ruleLink(r)}; evidence: ${r.evidence.map(ev).join(', ')}; code: ${r.usedBy.map(code).join(', ')}`);
  }
  return out.join('\n') + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await buildIndex();
  const file = path.join(ROOT, INDEX_FILE);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) { console.error(`${INDEX_FILE} is stale: run node scripts/gen-origin-rules-index.mjs`); process.exit(1); }
    console.log(`${INDEX_FILE} is current`);
  } else { fs.writeFileSync(file, text); console.log(`wrote ${INDEX_FILE}`); }
}
