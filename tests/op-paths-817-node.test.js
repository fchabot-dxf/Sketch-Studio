// a paths port whose worker the test drives: the page's server (op-derive.js) with its turns and its answers held
function manualPort() {
  const turns = [], answers = [], ran = [];
  let deliver = () => {};
  const server = createPathsServer({ post: (m) => { ran.push(m.id); answers.push(structuredClone(m)); }, schedule: (fn) => turns.push(fn) });
  return {
    kind: 'manual', post: (m) => server.receive(structuredClone(m)), listen: (fn) => { deliver = fn; }, close() {},
    run() { while (turns.length) turns.shift()(); }, // the worker works through its queue
    answer(order = null) { const list = order ? order.map((id) => answers.find((a) => a.id === id)) : answers.slice(); for (const a of list) { answers.splice(answers.indexOf(a), 1); deliver(a); } return list.map((a) => a.id); },
    queued: () => server.queued(), ran, answers,
  };
}
